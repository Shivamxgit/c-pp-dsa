#include <iostream>
using namespace std;

int main() {
    int x = 15, y = 25;

    cout << "x = " << x << ", y = " << y << endl;
    cout << "Is x greater than y? " << (x > y) << endl;
    cout << "Is x less than y? " << (x < y) << endl;
    cout << "Are x and y equal? " << (x == y) << endl;
    cout << "Are x and y not equal? " << (x != y) << endl;

    return 0;
}